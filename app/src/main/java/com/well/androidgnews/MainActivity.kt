package com.well.androidgnews

import android.os.Bundle
import android.widget.Toast
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.activity.enableEdgeToEdge
import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.ui.platform.LocalContext
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import androidx.lifecycle.viewmodel.compose.viewModel
import androidx.navigation.NavController
import androidx.navigation.compose.NavHost
import androidx.navigation.compose.composable
import androidx.navigation.compose.rememberNavController
import com.well.androidgnews.data.auth.User
import com.well.androidgnews.data.model.Article
import com.well.androidgnews.di.AppDependencies
import com.well.androidgnews.ui.favorites.FavoritesScreen
import com.well.androidgnews.ui.favorites.FavoritesViewModel
import com.well.androidgnews.ui.headlines.HeadlinesScreen
import com.well.androidgnews.ui.headlines.HeadlinesViewModel
import com.well.androidgnews.ui.login.LoginScreen
import com.well.androidgnews.ui.login.LoginViewModel
import com.well.androidgnews.ui.login.clearGoogleCredentialState
import com.well.androidgnews.ui.search.SearchScreen
import com.well.androidgnews.ui.search.SearchViewModel
import com.well.androidgnews.ui.session.SessionViewModel
import com.well.androidgnews.ui.theme.NewsTheme
import com.well.androidgnews.util.openUrl
import kotlinx.coroutines.launch

class MainActivity : ComponentActivity() {

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        val dependencies = (application as NewsApplication).dependencies
        // Generated by the google-services plugin from google-services.json.
        val googleWebClientId = getString(R.string.default_web_client_id)

        setContent {
            NewsTheme {
                val analytics = dependencies.analytics
                val session = viewModel { SessionViewModel(dependencies.authRepository, analytics) }
                val user by session.currentUser.collectAsStateWithLifecycle()

                // Attach (or clear) the pseudonymous uid on analytics events and crash reports.
                LaunchedEffect(user?.id) { analytics.setUser(user?.id) }

                // Reading news requires an account: signed out, the login screen is all there is.
                val signedIn = user
                if (signedIn == null) {
                    LaunchedEffect(Unit) { analytics.screenViewed(Routes.LOGIN) }
                    LoginScreen(
                        viewModel = viewModel { LoginViewModel(dependencies.authRepository, analytics) },
                        googleWebClientId = googleWebClientId,
                    )
                } else {
                    SignedInApp(dependencies, signedIn, onSignOut = session::signOut)
                }
            }
        }
    }

    @Composable
    private fun SignedInApp(dependencies: AppDependencies, user: User, onSignOut: () -> Unit) {
        val navController = rememberNavController()
        val context = LocalContext.current
        val scope = rememberCoroutineScope()
        val repository = dependencies.newsRepository
        val analytics = dependencies.analytics
        // Activity-scoped so every screen shares one favorites list and its hearts stay in sync.
        val favorites = viewModel {
            FavoritesViewModel(dependencies.authRepository, dependencies.favoritesRepository, analytics)
        }
        val openArticle: (Article) -> Unit = {
            analytics.articleOpened(it)
            context.openUrl(it.url)
        }

        // One screen_view per destination: Compose screens all live in this single Activity, so
        // Analytics' automatic Activity-based screen tracking can't tell them apart.
        DisposableEffect(navController) {
            val listener = NavController.OnDestinationChangedListener { _, destination, _ ->
                destination.route?.let(analytics::screenViewed)
            }
            navController.addOnDestinationChangedListener(listener)
            onDispose { navController.removeOnDestinationChangedListener(listener) }
        }
        val favoriteUrls by favorites.favoriteUrls.collectAsStateWithLifecycle()

        LaunchedEffect(favorites) {
            favorites.errors.collect { Toast.makeText(context, it, Toast.LENGTH_SHORT).show() }
        }

        NavHost(navController = navController, startDestination = Routes.HEADLINES) {
            composable(Routes.HEADLINES) {
                HeadlinesScreen(
                    viewModel = viewModel { HeadlinesViewModel(repository) },
                    favoriteUrls = favoriteUrls,
                    onToggleFavorite = favorites::toggle,
                    accountLabel = user.email ?: user.name ?: "已登入",
                    onSearchClick = { navController.navigate(Routes.SEARCH) },
                    onFavoritesClick = { navController.navigate(Routes.FAVORITES) },
                    onSignOut = {
                        onSignOut()
                        scope.launch { clearGoogleCredentialState(context) }
                    },
                    onArticleClick = openArticle,
                )
            }
            composable(Routes.SEARCH) {
                SearchScreen(
                    viewModel = viewModel { SearchViewModel(repository, analytics) },
                    favoriteUrls = favoriteUrls,
                    onToggleFavorite = favorites::toggle,
                    onBack = { navController.popBackStack() },
                    onArticleClick = openArticle,
                )
            }
            composable(Routes.FAVORITES) {
                FavoritesScreen(
                    viewModel = favorites,
                    onBack = { navController.popBackStack() },
                    onArticleClick = openArticle,
                )
            }
        }
    }

    private object Routes {
        const val HEADLINES = "headlines"
        const val SEARCH = "search"
        const val FAVORITES = "favorites"
        const val LOGIN = "login"
    }
}
